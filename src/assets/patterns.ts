/**
 * Notation:
 *   '0' = empty
 *   '1'-'9' = IDs 1-9
 *   'a'-'z' = IDs 10-35
 *   'A' = ID 36
 */

export function parsePattern(rows: string[]): number[][] {
  const map: Record<string, number> = { '0': 0 }
  // 1-9
  for (let i = 1; i <= 9; i++) map[String(i)] = i
  // a-z → 10-35
  for (let i = 0; i < 26; i++) map[String.fromCharCode(97 + i)] = 10 + i
  // A → 36
  map['A'] = 36
  return rows.map(row => [...row].map(ch => map[ch] ?? 0))
}

